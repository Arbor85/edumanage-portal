#!/usr/bin/env node
// Downloads exercise images from hasaneyldrm/exercises-dataset and generates
// modern/src/data/exerciseImageMap.ts for frontend use.
// Run with: node scripts/download-exercise-images.js

import { writeFile, mkdir, access } from 'fs/promises';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..');

const DATASET_BASE = 'https://raw.githubusercontent.com/hasaneyldrm/exercises-dataset/main';
const EXERCISES_JSON_URL = `${DATASET_BASE}/data/exercises.json`;
const IMAGES_OUT_DIR = join(REPO_ROOT, 'modern', 'public', 'images', 'exercises');
const IMAGE_MAP_OUT = join(REPO_ROOT, 'modern', 'src', 'data', 'exerciseImageMap.ts');

async function fileExists(path) {
  try { await access(path); return true; } catch { return false; }
}

async function downloadFile(url, destPath) {
  if (await fileExists(destPath)) return false;
  const res = await fetch(url);
  if (!res.ok) return false;
  await writeFile(destPath, Buffer.from(await res.arrayBuffer()));
  return true;
}

async function main() {
  await mkdir(IMAGES_OUT_DIR, { recursive: true });
  await mkdir(join(REPO_ROOT, 'modern', 'src', 'data'), { recursive: true });

  console.log('Fetching exercises.json...');
  const res = await fetch(EXERCISES_JSON_URL);
  if (!res.ok) throw new Error(`Failed to fetch exercises list: ${res.status}`);
  const exercises = await res.json();
  console.log(`Found ${exercises.length} exercises.`);

  const map = {};
  let downloaded = 0;
  let skipped = 0;

  for (let i = 0; i < exercises.length; i++) {
    const ex = exercises[i];
    const imageFilename = ex.image?.replace('images/', '');
    const gifFilename = ex.gif_url?.replace('videos/', '');

    let imagePath = null;
    let gifPath = null;

    if (imageFilename) {
      const dest = join(IMAGES_OUT_DIR, imageFilename);
      const got = await downloadFile(`${DATASET_BASE}/images/${imageFilename}`, dest);
      if (got) downloaded++; else skipped++;
      imagePath = `/images/exercises/${imageFilename}`;
    }

    if (gifFilename) {
      const dest = join(IMAGES_OUT_DIR, gifFilename);
      const got = await downloadFile(`${DATASET_BASE}/videos/${gifFilename}`, dest);
      if (got) downloaded++; else skipped++;
      gifPath = `/images/exercises/${gifFilename}`;
    }

    if (ex.name && (imagePath || gifPath)) {
      map[ex.name.toLowerCase()] = { imagePath, gifPath };
    }

    if ((i + 1) % 100 === 0 || i === exercises.length - 1) {
      process.stdout.write(`\r[${i + 1}/${exercises.length}] downloaded: ${downloaded}, skipped: ${skipped}   `);
    }
  }

  console.log('\nWriting exerciseImageMap.ts...');
  const ts = `// Auto-generated by scripts/download-exercise-images.js — do not edit manually.
// Maps lowercase exercise name → local image paths.
export const exerciseImageMap: Record<string, { imagePath: string | null; gifPath: string | null }> = ${JSON.stringify(map, null, 2)};
`;
  await writeFile(IMAGE_MAP_OUT, ts, 'utf8');
  console.log(`Done. ${Object.keys(map).length} entries written to exerciseImageMap.ts`);
  console.log(`Images: ${downloaded} downloaded, ${skipped} already existed.`);
}

main().catch(err => { console.error(err); process.exit(1); });
